// Illustration prompts and status (art/STYLE.md): `pnpm art` regenerates art/PROMPTS.md and lists
// which cards still lack a picture in art/cards/.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { loadPack } from '../content/index.ts';
import { ART_NEGATIVE, artPrompt, artSubjects } from '../content/packs/fantasy/art.ts';
import { fantasyPack } from '../content/packs/fantasy/index.ts';

const ART_DIR = new URL('../../art/', import.meta.url);
const CARDS_DIR = new URL('cards/', ART_DIR);
/** Delivered pictures stay small: they ship inside the static build (art/STYLE.md §4). */
const MAX_BYTES = 120 * 1024;

const content = loadPack(fantasyPack);
const ru = fantasyPack.locales.ru;
const files = readdirSync(CARDS_DIR).filter((name) => /\.(webp|png|jpe?g)$/.test(name));
const fileOf = new Map(files.map((name) => [name.replace(/\.[^.]+$/, ''), name]));

const lines = [
  '# Card illustration prompts',
  '',
  '<!-- Generated by `pnpm art` from src/content/packs/fantasy/art.ts. Do not edit by hand. -->',
  '',
  'Style, delivery and credits: [STYLE.md](STYLE.md). Save each picture as',
  '`art/cards/<card id>.webp` and add a row to [CREDITS.md](CREDITS.md).',
  '',
  `**Negative prompt (all cards):** ${ART_NEGATIVE}`,
  '',
];
let kind = '';
for (const card of content.cards.values()) {
  if (card.kind !== kind) {
    kind = card.kind;
    lines.push(`## ${kind}`, '');
  }
  const name = ru[`${card.id}.name`] ?? ru[`${card.id}.v0.name`] ?? '';
  const done = fileOf.has(card.id) ? ' ✅' : '';
  lines.push(
    `### \`${card.id}\` — ${name}${done}`,
    '',
    '```text',
    artPrompt(artSubjects[card.id] ?? ''),
    '```',
    '',
  );
}
writeFileSync(new URL('PROMPTS.md', ART_DIR), lines.join('\n'));

const missing = [...content.cards.keys()].filter((id) => !fileOf.has(id));
const orphans = [...fileOf.keys()].filter((id) => !content.cards.has(id));
const heavy = files.filter((name) => statSync(new URL(name, CARDS_DIR)).size > MAX_BYTES);
console.log(`art/PROMPTS.md: ${String(content.cards.size)} prompts`);
console.log(
  `pictures: ${String(content.cards.size - missing.length)}/${String(content.cards.size)}`,
);
if (orphans.length > 0) console.log(`unknown card ids: ${orphans.join(', ')}`);
if (heavy.length > 0) console.log(`over ${String(MAX_BYTES / 1024)} KB: ${heavy.join(', ')}`);
if (orphans.length > 0 || heavy.length > 0) process.exitCode = 1;
